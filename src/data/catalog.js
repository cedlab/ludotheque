const pad = (n) => String(n).padStart(4, '0');

export function catalogGames() {
  return GAMES.map(([name, minPlayers, maxPlayers, duration, minAge, scoring, extra = {}], i) => ({
    id: `00000000-0000-4000-8000-00000001${pad(i + 1)}`,
    createdAt: T,
    updatedAt: REVISED,
    deleted: false,
    name,
    logo: null,
    minPlayers,
    maxPlayers,
    duration,
    minAge,
    scoring: structuredClone(scoring),
    dice: null,
    icon: ICONS[name] || null,
    styles: STYLES[name] || [],
    notes: '',
    ...structuredClone(extra),
  })).map((g) => (REMOVED.has(g.name) ? { ...g, deleted: true, updatedAt: REMOVED_AT } : g));
}

/** Nom simplifié pour repérer un même jeu saisi à la main (accents, ponctuation…). */
export function normalizeName(name = '') {
  return name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

/**
 * Jeux du catalogue à fusionner : on écarte ceux qui existent déjà sous un
 * autre identifiant (même nom, ajouté à la main), pour éviter les doublons.
 */
export function catalogToMerge(existingGames = []) {
  const ownIds = new Set(existingGames.map((g) => g.id));
  const names = new Set(existingGames.filter((g) => !g.deleted).map((g) => normalizeName(g.name)));
  // Ce que la famille a choisi (favori, liste) ne doit pas être perdu à une mise à jour du catalogue.
  const personal = new Map(existingGames.map((g) => [g.id, { favorite: g.favorite, favoriteOf: g.favoriteOf, status: g.status, review: g.review }]));
  // Les jeux retirés (supprimés) passent toujours : leur suppression doit se propager.
  return catalogGames()
    .filter((g) => g.deleted || ownIds.has(g.id) || !names.has(normalizeName(g.name)))
    .map((g) => {
      const mine = personal.get(g.id);
      if (!mine || g.deleted) return g;
      const out = { ...g };
      if (mine.favorite) out.favorite = true;
      if (Array.isArray(mine.favoriteOf) && mine.favoriteOf.length) out.favoriteOf = [...mine.favoriteOf];
      if (mine.status) out.status = mine.status;
      if (mine.review) out.review = mine.review;
      return out;
    });
}
